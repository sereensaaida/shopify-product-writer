/**
 * Builds a Liquid theme section from the generated benefits.
 * This part is a plain template (no AI), so the Liquid is predictable and valid.
 * Drop the output into your theme's /sections folder, then add it from the theme editor.
 */
const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

export function buildSection({ heading, benefits }) {
  const blocks = benefits
    .map(
      (b) => `    {
      "type": "benefit",
      "settings": { "text": "${esc(b)}" }
    }`
    )
    .join(",\n");

  return `{%- comment -%} Generated by shopify-ai-product-writer {%- endcomment -%}
<section class="product-benefits" style="padding: {{ section.settings.padding }}px 20px;">
  {%- if section.settings.heading != blank -%}
    <h2>{{ section.settings.heading | escape }}</h2>
  {%- endif -%}
  <ul style="list-style: none; padding: 0; display: grid; gap: 12px;">
    {%- for block in section.blocks -%}
      <li {{ block.shopify_attributes }}>&#10003; {{ block.settings.text | escape }}</li>
    {%- endfor -%}
  </ul>
</section>

{% schema %}
{
  "name": "Product benefits",
  "settings": [
    { "type": "text", "id": "heading", "label": "Heading", "default": "${esc(heading)}" },
    { "type": "range", "id": "padding", "label": "Vertical padding", "min": 0, "max": 80, "step": 4, "unit": "px", "default": 32 }
  ],
  "blocks": [
    {
      "type": "benefit",
      "name": "Benefit",
      "settings": [{ "type": "text", "id": "text", "label": "Text", "default": "Benefit" }]
    }
  ],
  "presets": [
    {
      "name": "Product benefits",
      "blocks": [
${blocks}
      ]
    }
  ]
}
{% endschema %}
`;
}
